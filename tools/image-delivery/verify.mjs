// Development-only: verify CDN responses before opting sources into delivery.
// Usage: node tools/image-delivery/verify.mjs catalog.json https://preview.netlify.app report.json
import fs from 'node:fs/promises';
import sharp from 'sharp';
import { fileURLToPath } from 'node:url';

export const SIZES = Object.freeze({ small: 720, medium: 1440, brand: 252 });
export function sourceKey(source) {
  const url = new URL(source, 'https://images.invalid/');
  if (url.origin !== 'https://images.invalid') return '';
  // Only v is a cache buster. Identity-bearing queries (notably Blob key) stay.
  url.searchParams.delete('v');
  url.hash = '';
  return url.pathname + url.search;
}
export function deliveryUrl(source, size) {
  const url = new URL(source, 'https://images.invalid/');
  return '/.netlify/images?' + new URLSearchParams({
    url: url.pathname + url.search, w: String(size), h: String(size),
    fit: 'contain', q: '85', fm: 'webp',
  });
}
export async function inspect(bytes) {
  const m = await sharp(bytes).metadata();
  const rotated = [5, 6, 7, 8].includes(m.orientation);
  return { bytes: bytes.length, width: rotated ? m.height : m.width,
    height: rotated ? m.width : m.height, format: m.format,
    opaque: !m.hasAlpha || (await sharp(bytes).stats()).isOpaque };
}
export function acceptable(source, delivered, size) {
  // Permit only the subpixel rounding inherent in proportional resizing.
  const expectedScale = Math.min(1, size / Math.max(source.width, source.height));
  return delivered.bytes < source.bytes &&
    delivered.width <= source.width && delivered.height <= source.height &&
    Math.abs(delivered.width - source.width * expectedScale) <= 1 &&
    Math.abs(delivered.height - source.height * expectedScale) <= 1 &&
    (source.opaque || !delivered.opaque);
}

async function main() {
  const [catalogFile, origin, reportFile] = process.argv.slice(2);
  if (!catalogFile || !origin || !reportFile) throw new Error('catalog, preview origin, report required');
  const catalog = JSON.parse(await fs.readFile(catalogFile));
  const html = await fs.readFile('index.html', 'utf8');
  const embedded = [...html.matchAll(/<img\b[^>]*>/g)].map(m => (m[0].match(/\bdata-original-src="([^"]+)"/) || m[0].match(/\bsrc="([^"]+)"/))?.[1]?.replaceAll('&amp;', '&')).filter(Boolean);
  const sources = [...new Set([...catalog.products.flatMap(p => p.images || []), ...embedded])]
    .filter(s => !s.startsWith('/.netlify/images') && !/^(https?:|data:)/.test(s));
  const byKey = new Map();
  for (const source of sources) if (!byKey.has(sourceKey(source))) byKey.set(sourceKey(source), source);
  const pending = [...byKey.entries()];
  const report = [];
  const manifest = {};
  async function get(url) {
    const r = await fetch(new URL(url, origin), { signal: AbortSignal.timeout(60000) });
    if (!r.ok || !r.headers.get('content-type')?.startsWith('image/')) throw new Error('HTTP ' + r.status);
    return Buffer.from(await r.arrayBuffer());
  }
  await Promise.all(Array.from({ length: 6 }, async () => {
    while (pending.length) {
      const [key, source] = pending.shift();
      const row = { key, source, sizes: {} };
      try {
        let original;
        const sourceUrl = new URL(source, origin);
        if (sourceUrl.pathname.startsWith('/.netlify/')) original = await get(source);
        else original = await fs.readFile('.' + decodeURIComponent(sourceUrl.pathname));
        row.original = await inspect(original);
        const classes = key === '/assets/media/maria-david-luciano.png' ? ['brand'] : ['small', 'medium'];
        for (const cls of classes) {
          try {
            const url = deliveryUrl(source, SIZES[cls]);
            const delivered = await inspect(await get(url));
            const approved = acceptable(row.original, delivered, SIZES[cls]);
            row.sizes[cls] = { ...delivered, approved, url };
            if (approved) (manifest[key] ||= []).push(cls);
          } catch (e) { row.sizes[cls] = { error: e.message }; }
        }
      } catch (e) { row.error = e.message; }
      report.push(row);
      await fs.appendFile(reportFile + '.jsonl', JSON.stringify(row) + '\n');
      if (report.length % 50 === 0) console.log('Verified ' + report.length + '/' + byKey.size);
    }
  }));
  const sorted = Object.fromEntries(Object.entries(manifest).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0));
  const entries = Object.entries(sorted).map(([key, sizes]) => '  ' + JSON.stringify(key) + ': ' + JSON.stringify(sizes));
  await fs.writeFile('js/image-delivery-manifest.js', '// Generated by tools/image-delivery/verify.mjs. Verified CDN sizes; originals stay canonical.\nwindow.__imageDeliveryManifest = {\n' + entries.join(',\n') + '\n};\n');
  await fs.writeFile(reportFile, JSON.stringify({ origin, sizes: SIZES, report: report.sort((a,b)=>a.key.localeCompare(b.key)) }, null, 2));
  console.log(JSON.stringify({ sources: report.length, approved: Object.keys(manifest).length, errors: report.filter(r=>r.error).length, rejectedSizes: report.flatMap(r=>Object.values(r.sizes)).filter(r=>!r.approved).length }));
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
